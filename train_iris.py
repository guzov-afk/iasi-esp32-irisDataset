"""Train an Iris MLP on the PC and export float32 weights for ESP32.

The generated firmware evaluates the same dense/relu/softmax network in C++.
This baseline deliberately does NOT use TensorFlow Lite Micro.
"""
from __future__ import annotations
import argparse
import csv
import json
from pathlib import Path
import warnings
import numpy as np
from sklearn.datasets import load_iris
from sklearn.metrics import accuracy_score, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.exceptions import ConvergenceWarning

ROOT = Path(__file__).resolve().parent


def array_c(name: str, a: np.ndarray) -> str:
    a = np.asarray(a, dtype=np.float32)
    def f(v):
        return f'{float(v):.9g}f' if '.' in f'{float(v):.9g}' or 'e' in f'{float(v):.9g}' else f'{float(v):.9g}.0f'
    if a.ndim == 1:
        return f'static const float {name}[{len(a)}] = {{' + ', '.join(map(f, a)) + '};\n'
    if a.ndim == 2:
        lines = ['  {' + ', '.join(map(f, row)) + '}' for row in a]
        return f'static const float {name}[{a.shape[0]}][{a.shape[1]}] = {{\n' + ',\n'.join(lines) + '\n};\n'
    raise ValueError('Unsupported dimensions')


def main():
    p = argparse.ArgumentParser(description='Train/Export Iris MLP to ESP32')
    p.add_argument('--h1', type=int, default=16, help='first hidden layer width')
    p.add_argument('--h2', type=int, default=8, help='second hidden layer width')
    p.add_argument('--lr', type=float, default=0.01, help='initial learning rate')
    p.add_argument('--seed', type=int, default=42)
    p.add_argument('--epochs', type=int, default=1500)
    args = p.parse_args()
    if min(args.h1, args.h2, args.epochs) < 1 or args.lr <= 0:
        p.error('Layer widths and epochs must be >= 1; learning rate > 0')

    iris = load_iris()
    x_train, x_test, y_train, y_test = train_test_split(
        iris.data.astype(np.float32), iris.target, test_size=0.2,
        random_state=args.seed, stratify=iris.target
    )
    scaler = StandardScaler().fit(x_train)  # Critical: no test-set leakage
    x_train_z = scaler.transform(x_train).astype(np.float32)
    x_test_z = scaler.transform(x_test).astype(np.float32)
    model = MLPClassifier(hidden_layer_sizes=(args.h1, args.h2),
                          activation='relu', solver='adam',
                          learning_rate_init=args.lr, max_iter=args.epochs,
                          n_iter_no_change=100, random_state=args.seed)
    with warnings.catch_warnings():
        warnings.simplefilter('ignore', ConvergenceWarning)
        model.fit(x_train_z, y_train)
    pred_train = model.predict(x_train_z)
    pred_test = model.predict(x_test_z)
    accuracy_train = accuracy_score(y_train, pred_train)
    accuracy_test = accuracy_score(y_test, pred_test)
    cm = confusion_matrix(y_test, pred_test, labels=[0, 1, 2])

    lines = [
        '// AUTO-GENERATED BY train_iris.py -- DO NOT EDIT BY HAND',
        '#pragma once',
        '// Features: sepal length, sepal width, petal length, petal width (cm)',
        'constexpr int IRIS_INPUTS = 4;',
        f'constexpr int IRIS_H1 = {args.h1};',
        f'constexpr int IRIS_H2 = {args.h2};',
        'constexpr int IRIS_OUTPUTS = 3;',
        array_c('IRIS_MEAN', scaler.mean_),
        array_c('IRIS_SCALE', scaler.scale_),
        array_c('IRIS_W1', model.coefs_[0]),
        array_c('IRIS_B1', model.intercepts_[0]),
        array_c('IRIS_W2', model.coefs_[1]),
        array_c('IRIS_B2', model.intercepts_[1]),
        array_c('IRIS_W3', model.coefs_[2]),
        array_c('IRIS_B3', model.intercepts_[2]),
    ]
    (ROOT / 'include').mkdir(exist_ok=True)
    (ROOT / 'include' / 'iris_weights.h').write_text('\n'.join(lines), encoding='utf8')
    (ROOT / 'results').mkdir(exist_ok=True)
    with (ROOT / 'results' / 'iris_test.csv').open('w', newline='', encoding='utf8') as file:
        writer = csv.writer(file)
        writer.writerow(['sepal_length', 'sepal_width', 'petal_length', 'petal_width', 'label'])
        for row, label in zip(x_test, y_test):
            writer.writerow([*(format(float(v), '.7g') for v in row), int(label)])

    metrics = {
        'seed': args.seed, 'hidden_layers': [args.h1, args.h2],
        'learning_rate': args.lr, 'max_iter': args.epochs,
        'training_examples': len(y_train), 'test_examples': len(y_test),
        'train_accuracy': accuracy_train, 'test_accuracy': accuracy_test,
        'confusion_matrix': cm.tolist(),
        'weights_biases_floats': int(sum(v.size for v in model.coefs_ + model.intercepts_)),
        'weights_biases_bytes_float32': int(4 * sum(v.size for v in model.coefs_ + model.intercepts_)),
    }
    (ROOT / 'results' / 'metrics.json').write_text(json.dumps(metrics, indent=2), encoding='utf8')
    print(f'MLP 4 -> {args.h1} -> {args.h2} -> 3')
    print(f'Train accuracy: {accuracy_train:.3f} | Test accuracy: {accuracy_test:.3f}')
    print('Confusion matrix (rows=true, cols=predicted):\n', cm)
    print(f'Weights + biases (float32): {metrics["weights_biases_bytes_float32"]} bytes')
    print('Generated include/iris_weights.h and results/iris_test.csv')

    # Check the exact float32 on-device mathematical implementation against sklearn.
    w = [np.asarray(a, dtype=np.float32) for a in model.coefs_]
    b = [np.asarray(a, dtype=np.float32) for a in model.intercepts_]
    h1 = np.maximum(0, x_test_z @ w[0] + b[0])
    h2 = np.maximum(0, h1 @ w[1] + b[1])
    z = h2 @ w[2] + b[2]
    embedded_pred = z.argmax(axis=1)
    if not np.array_equal(embedded_pred, pred_test):
        raise RuntimeError('Float32 firmware arithmetic disagrees with sklearn on holdout!')
    print('PASS: standalone float32 forward pass matches sklearn labels on test set.')


if __name__ == '__main__':
    main()
